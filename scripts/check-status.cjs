const assert = require("node:assert/strict");
const fs = require("node:fs");
const vm = require("node:vm");
const ts = require("typescript");
function load(path, deps = {}) {
  const exports = {};
  vm.runInNewContext(ts.transpileModule(fs.readFileSync(path, "utf8"), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText, { exports, require: (id) => deps[id] || require(id), Map, Set });
  return exports;
}
const engine = load("src/lib/ticket-status.ts", { "@/lib/design-time": load("src/lib/design-time.ts") });
const parser = load("src/lib/ticket-parser.ts");
const base = { id: "10", client: "Example", title: "Test", assignee: "Alex", designTime: "2:00", status: "Assigned", sources: ["clients"] };
const observe = (entries, status, extra = {}) => engine.applyObservation(entries, { ...base, status, ...extra });
assert.equal(observe([], "Draft").length, 0);
assert.equal(observe([], "Inactive").length, 0);
assert.equal(observe([], "Assigned")[0].completion, 0);
assert.equal(observe([], "In Progress (paused)")[0].completion, 0.5);
let entries = observe([], "In Progress");
entries = observe(entries, "Quality Review");
assert.equal(entries[0].completion, 0.8);
entries = observe(entries, "Customer Review");
assert.equal(entries[0].completion, 1);
entries = observe(entries, "Open (Revision)");
assert.equal(entries.length, 2);
assert.equal(entries[0].status, "Customer Review");
assert.equal(entries[0].completion, 1);
assert.equal(entries[1].completion, 0);
assert.equal(entries[1].entryId, "10:2");
assert.equal(observe(entries, "Open (Revision)").length, 2);
entries = observe(entries, "Assigned", { designTime: "1:00" });
assert.equal(entries[0].designTime, "2:00");
assert.equal(entries[1].designTime, "1:00");
assert.equal(observe(entries, "Open (Revision)").length, 3);
let wip = observe([], "Incomplete (WIP)");
assert.equal(wip[0].completion, 0);
wip = observe(wip, "In Progress");
wip = observe(wip, "Incomplete (WIP)");
assert.equal(wip[0].completion, 1);
assert.equal(wip[0].lockedWip, true);
assert.equal(observe(wip, "Open (Revision)").length, 1);
assert.equal(observe(wip, "Assigned", { designTime: "9:00" })[0].designTime, "2:00");
assert.equal(observe([], "Incomplete (WIP)")[0].lockedWip, false);
assert.equal(engine.countedMinutes(observe(wip, "Cancelled")[0]), 0);
assert.equal(engine.countedMinutes(observe([], "Customer Clarification")[0]), 0);
assert.equal(observe(observe([], "In Progress"), "Open")[0].completion, 1);
assert.ok(observe(observe([], "In Progress"), "Open")[0].reviewFlag);
assert.equal(observe(observe([], "Quality Review"), "Open (Revision)")[0].completion, 1);
assert.equal(observe([], "Closed")[0].completion, 1);
assert.equal(observe([], "Archived")[0].completion, 1);
assert.equal(engine.completedMinutes(observe([], "Quality Review")[0]), 96);
assert.equal(parser.parseTicketStatus('<div role="status" aria-label="Ticket Status">Open (Revision)</div>'), "Open (Revision)");
assert.equal(parser.parseTicketStatus('<select aria-label="State"><option selected data-label="Customer Review">review</option></select>'), "Customer Review");
assert.throws(() => parser.parseTicketStatus("<div>Unexpected</div>"));
const scopes = [["GD"], ["GD", "PD"], ["GD", "PD", "FIG"], ["CI", "GD"], ["MG"], ["VE"]];
scopes.forEach((scopes, index) => assert.equal(engine.scopeRank({ scopes }), index));
console.log("Status checks passed: progress, review, revisions, repeated observations, WIP lock, cancellation, exclusions, detail parsing and scope order.");
